-- ============================================================
-- KIỂM TRA TỔNG QUAN
-- ============================================================

SELECT
    cm.course AS Course_ID,
    m.name AS Module_Type,
    e.coursemoduleid AS Module_ID,
    COUNT(DISTINCT e.userid) AS Interacted_Users,
    SUM(e.time_spent_seconds) AS Total_Time_Seconds
FROM mdl_local_module_daily_engagement e
INNER JOIN mdl_course_modules cm ON cm.id = e.coursemoduleid
INNER JOIN mdl_modules m ON m.id = cm.module
WHERE e.coursemoduleid BETWEEN 10001 AND 10008
GROUP BY cm.course, m.name, e.coursemoduleid
ORDER BY cm.course, e.coursemoduleid;