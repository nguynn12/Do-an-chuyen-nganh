import app from './src/app.js';
import {generateAuthToken} from './src/shared/services/tokenService.js';
import assert from 'node:assert/strict';
import pool from './src/config/database.js';
import {loadTeacherLearningAlerts} from './src/GiangVien/controllers/teacherController.js';
import {getStudentDashboardSummary} from './src/SinhVien/controllers/studentController.js';
import {ensureAlertStateSchema,storeAlertState,getAssignedCourses,insertClassBroadcast} from './src/GiangVien/services/learningAlertStateService.js';
await ensureAlertStateSchema();
const [[teacher]]=await pool.query("SELECT User_Key AS userKey,Moodle_User_ID AS moodleUserId FROM Dim_User WHERE Moodle_User_ID=2 AND LOWER(Primary_Role)='teacher'");
const courses=await getAssignedCourses(teacher.moodleUserId);assert.ok(courses.length);
const db=await pool.getConnection(),original=pool.query,originalGetConnection=pool.getConnection;
let server;
let checks=0;
try {
 await db.beginTransaction();pool.query=db.query.bind(db);
 const marker='AUDIT_ROLLBACK_'+Date.now();
 const recipientCount=await insertClassBroadcast(db,teacher,[courses[0]],{title:marker,desc:'Transaction-only regression; never committed.'});
 assert.ok(recipientCount>0);checks++;
 const [[count]]=await db.query('SELECT COUNT(*) AS n FROM fact_notification WHERE title=?',[marker]);
 assert.equal(count.n,recipientCount+1);checks++;
 const [[recipient]]=await db.query('SELECT u.* FROM fact_notification n JOIN Dim_User u ON u.User_Key=n.recipient_user_id WHERE n.title=? AND n.recipient_user_id<>? LIMIT 1',[marker,teacher.userKey]);
 const response={json(body){this.body=body;return this;},status(code){this.code=code;return this;}};
 await getStudentDashboardSummary({student:{userKey:recipient.User_Key},query:{},params:{}},response);
 assert.equal(response.code,undefined);assert.ok(response.body.notifications.some(item=>item.title===marker));checks+=2;
 const alerts=await loadTeacherLearningAlerts(teacher.moodleUserId);
 const copy=alerts.find(item=>item.title===marker);assert.ok(copy);assert.equal(copy.unread,false);checks+=2;
 const target=alerts.find(item=>item.type==='risk' || item.type==='deadline');assert.ok(target);
 await storeAlertState(teacher.userKey,[target.id],{read:true},db);
 let reload=await loadTeacherLearningAlerts(teacher.moodleUserId);
 assert.equal(reload.find(item=>item.id===target.id).unread,false);checks++;
 await storeAlertState(teacher.userKey,[target.id],{read:false},db);
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.equal(reload.find(item=>item.id===target.id).unread,true);checks++;
 await storeAlertState(teacher.userKey,[target.id],{read:false,deleted:true},db);
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.ok(!reload.some(item=>item.id===target.id));checks++;
 const ids=reload.map(item=>item.id);assert.equal(new Set(ids).size,ids.length);checks++;
 await storeAlertState(teacher.userKey,ids,{read:true},db);
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.equal(reload.filter(item=>item.unread).length,0);checks++;
 const [[state]]=await db.query('SELECT Is_Read FROM App_Learning_Alert_State WHERE User_Key=? AND Alert_ID=?',[teacher.userKey,copy.id]);assert.equal(state.Is_Read,1);checks++;
 const [[account]] = await db.query('SELECT Username, Role FROM App_User_Account WHERE User_Key = ? AND Is_Active = 1 LIMIT 1',[teacher.userKey]);
 const token=generateAuthToken({...teacher,username:account.Username,role:account.Role});
 pool.getConnection=async()=>({query:db.query.bind(db),beginTransaction:async()=>{},commit:async()=>{},rollback:async()=>{},release(){}});
 server=app.listen(0,'127.0.0.1'); await new Promise(resolve=>server.once('listening',resolve));
 const base=`http://127.0.0.1:${server.address().port}/api/teachers/${teacher.moodleUserId}/learning-alerts`;
 const call=async(path,method,body)=>fetch(base+path,{method,headers:{'Content-Type':'application/json',Authorization:`Bearer ${token}`},...(body?{body:JSON.stringify(body)}:{})});
 let responseHttp=await call('/'+encodeURIComponent(copy.id),'PATCH',{read:false});assert.equal(responseHttp.status,200);checks++;
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.equal(reload.find(item=>item.id===copy.id).unread,true);checks++;
 responseHttp=await call('/read-all','PUT',{read:true});assert.equal(responseHttp.status,200);checks++;
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.ok(reload.every(item=>!item.unread));checks++;
 responseHttp=await call('/'+encodeURIComponent(copy.id),'DELETE');assert.equal(responseHttp.status,200);checks++;
 reload=await loadTeacherLearningAlerts(teacher.moodleUserId);assert.ok(!reload.some(item=>item.id===copy.id));checks++;
 const httpMarker=marker+'_HTTP';
 responseHttp=await call('/broadcast','POST',{title:httpMarker,desc:'HTTP transaction-only test',courseId:courses[0].Moodle_Course_ID,type:'deadline'});
 assert.equal(responseHttp.status,201);const sent=await responseHttp.json();assert.equal(sent.recipientCount,recipientCount);checks+=2;
 const [[httpRows]]=await db.query("SELECT COUNT(*) AS n FROM fact_notification WHERE title=? AND notification_type='DEADLINE'",[httpMarker]);
 assert.equal(httpRows.n,recipientCount+1);checks++;
 console.log(`PASS ${checks} notification transaction checks: recipients, student inbox, sender copy, stable IDs, read/unread/delete/read-all persistence. Rolled back.`);
} finally {if(server)await new Promise(resolve=>server.close(resolve));pool.getConnection=originalGetConnection;pool.query=original;await db.rollback();db.release();await pool.end();}
